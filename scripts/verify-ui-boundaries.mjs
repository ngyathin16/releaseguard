import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { chromium } from 'playwright';

const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:4318';
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : process.platform === 'win32' ? { channel: 'msedge' } : {}) });
const page = await browser.newPage();
page.setDefaultTimeout(120000);
const report = { capturedAt: new Date().toISOString(), base, checks: [], passed: false, scope: 'Real server for policy validation/start/stop; explicitly intercepted state responses for uncertain control, disconnect and historical-state UI boundaries.' };
const check = text => { report.checks.push(text); process.stdout.write(`Passed: ${text}\n`); };
async function state() { return await (await fetch(`${base}/api/state`)).json(); }
let starts = 0;
page.on('request', request => { if (request.method() === 'POST' && request.url() === `${base}/api/runs`) starts++; });
try {
  await page.goto(base);
  await page.getByRole('button', { name: 'Reset workbench', exact: true }).click();
  await page.getByRole('heading', { name: 'A little traffic. A considered decision.' }).waitFor();
  const initial = await state();
  await page.getByText('Edit policy for the next run', { exact: true }).click();
  const editor = page.getByRole('textbox', { name: 'Next-run policy' });
  await editor.fill('');
  await page.waitForResponse(response => response.url() === `${base}/api/state`);
  assert.equal(await editor.inputValue(), '');
  await page.getByRole('button', { name: 'Start canary' }).click();
  await page.getByRole('alert').filter({ hasText: 'next-run policy is invalid' }).waitFor();
  assert.equal(starts, 0);
  await editor.fill('{"not":"a policy"}');
  await page.getByRole('button', { name: 'Start canary' }).click();
  await page.getByRole('alert').filter({ hasText: 'next-run policy is invalid' }).waitFor();
  assert.equal(starts, 0);
  check('Empty policy survives polling; malformed JSON/schema cannot dispatch a start');
  const policy = { ...initial.defaults, errorTolerance: 0.015 };
  await editor.fill(JSON.stringify(policy));
  await page.getByText('≤ 1.5 pp', { exact: true }).waitFor();
  await page.getByRole('spinbutton', { name: 'Workload seed' }).fill('');
  await page.getByRole('button', { name: 'Start canary' }).click();
  await page.getByRole('alert').filter({ hasText: 'Enter a workload seed' }).waitFor();
  assert.equal(starts, 0);
  check('Policy summary previews valid edits; an empty seed is rejected instead of becoming zero');
  await page.getByRole('spinbutton', { name: 'Workload seed' }).fill('1729');
  await page.getByRole('button', { name: 'Start canary' }).click();
  await page.getByRole('heading', { name: 'Current stage measurements' }).waitFor();
  assert.equal(await editor.isDisabled(), true);
  const started = await state();
  assert.equal(started.active.policy.errorTolerance, 0.015);
  await page.getByRole('heading', { name: 'Evidence supports the next step.' }).waitFor();
  const eligible = await state();
  assert.ok(eligible.active.liveMetrics.every(metric => metric.attempted > 0));
  check('Custom policy freezes in the real run; live measured counts are exposed without editing that policy');
  await page.getByRole('button', { name: 'Stop candidate traffic' }).click();
  await page.getByRole('heading', { name: 'Candidate traffic withdrawn.' }).waitFor();
  const stopped = await state();
  assert.equal(stopped.active.state, 'rolled back');
  assert.equal(stopped.active.decision.status, 'eligible to advance');
  assert.equal(await page.getByRole('button', { name: 'Advance to 25%' }).isDisabled(), true);
  check('A real eligible run that is manually stopped is shown as withdrawn, with advancement disabled');

  let override = { ...stopped, active: { ...eligible.active, state: 'stopping', rollback: null } };
  let disconnect = false;
  await page.route('**/api/state', async route => {
    if (disconnect) await route.abort('connectionrefused');
    else await route.fulfill({ json: override });
  });
  await page.getByRole('heading', { name: 'Withdrawing candidate traffic.' }).waitFor();
  await page.getByText('Exposure unconfirmed · awaiting router evidence', { exact: true }).waitFor();
  assert.equal(await page.getByText('Candidate exposure: 0%', { exact: true }).count(), 0);
  override = { ...stopped, active: { ...eligible.active, state: 'interrupted', rollback: null } };
  await page.getByRole('heading', { name: 'Interrupted. Verify before continuing.' }).waitFor();
  assert.equal(await page.getByText('Candidate exposure: 0%', { exact: true }).count(), 0);
  check('Intercepted stopping/unresolved-control states never claim confirmed zero exposure');
  disconnect = true;
  await page.getByRole('heading', { name: 'Connection lost. Advancement is locked.' }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Advance to 25%' }).isDisabled(), true);
  disconnect = false;
  override = stopped;
  await page.getByRole('heading', { name: 'Candidate traffic withdrawn.' }).waitFor();
  await page.waitForFunction(() => !document.querySelector('[role="alert"]'));
  check('Connection loss locks advancement; successful reconnection clears its stale error');
  override = { ...stopped, active: null };
  await page.getByRole('heading', { name: 'A little traffic. A considered decision.' }).waitFor();
  await page.locator('.history-button').first().click();
  await page.getByRole('heading', { name: 'Candidate traffic withdrawn.' }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Advance to 25%' }).isDisabled(), true);
  check('Saved stopped eligible evidence cannot advertise that the stopped run can advance');
  report.passed = true;
} finally {
  await writeFile(new URL('../docs/ui-boundary-verification.json', import.meta.url), JSON.stringify(report, null, 2) + '\n');
  await browser.close();
}
